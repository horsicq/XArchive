#include "xfdiimage.h"

#include <QFileInfo>
#include <QtEndian>

#include <new>

namespace {
const qint64 FDI_HEADER_SIZE = 14;
}  // namespace

XFDIImage::XFDIImage(QIODevice *pDevice) : XArchive(pDevice)
{
}

XFDIImage::~XFDIImage()
{
}

bool XFDIImage::parseContext(CONTEXT *pContext, PDSTRUCT *pPdStruct)
{
    if (!pContext || !isPdStructNotCanceled(pPdStruct)) return false;

    QIODevice *guardedSource = getDevice();
    if (!guardedSource || guardedSource->isSequential()) return false;

    CONTEXT context = {};
    context.nInputSize = guardedSource->size();
    if (context.nInputSize <= FDI_HEADER_SIZE) return false;

    const QByteArray baHeader = read_array_process(0, FDI_HEADER_SIZE, pPdStruct);
    if (!guardedSource || (baHeader.size() != FDI_HEADER_SIZE)) return false;
    if (baHeader.left(4) != QByteArray("FDI\0", 4)) return false;
    const uchar *pHeader = (const uchar *)baHeader.constData();

    const qint64 nDataOffset = qFromLittleEndian<quint16>(pHeader + 10);
    if ((nDataOffset < FDI_HEADER_SIZE) || (nDataOffset >= context.nInputSize)) return false;

    context.nDataOffset = nDataOffset;
    context.nCompressedSize = context.nInputSize - nDataOffset;
    context.nUncompressedSize = context.nCompressedSize;
    context.sFileName = QStringLiteral("1.img");

    *pContext = context;

    return true;
}

bool XFDIImage::isValid(PDSTRUCT *pPdStruct)
{
    QIODevice *guardedSource = getDevice();
    if (!guardedSource) return false;
    const qint64 nSavedPosition = guardedSource->pos();
    CONTEXT context = {};
    const bool bResult = parseContext(&context, pPdStruct);
    if (guardedSource) guardedSource->seek(nSavedPosition);

    return bResult;
}

bool XFDIImage::isValid(QIODevice *pDevice, PDSTRUCT *pPdStruct)
{
    XFDIImage archive(pDevice);
    return archive.isValid(pPdStruct);
}

